def add_heading(doc, text, level=1):
    p = doc.Paragraphs.Add()
    p.Range.Text = text
    style_id = {-1: -2, 1: -2, 2: -3, 3: -4}.get(level, -2)
    p.Style = style_id
    return p


def add_para(doc, text, bold=False):
    p = doc.Paragraphs.Add()
    r = p.Range
    r.Text = text
    r.Font.Name = "Times New Roman"
    r.Font.Size = 14
    r.Font.Bold = bold
    r.ParagraphFormat.SpaceAfter = 8
    r.ParagraphFormat.LineSpacingRule = 1
    r.ParagraphFormat.LineSpacing = 18
    return p


def add_code(doc, text):
    p = doc.Paragraphs.Add()
    r = p.Range
    r.Text = text
    r.Font.Name = "Consolas"
    r.Font.Size = 10
    r.ParagraphFormat.SpaceAfter = 10
    return p


def add_eq(doc, latex_like):
    p = doc.Paragraphs.Add()
    r = p.Range
    r.InsertAfter(latex_like)
    r.Font.Name = "Cambria Math"
    r.Font.Italic = True
    r.Font.Size = 14
    r.ParagraphFormat.Alignment = 1
    r.ParagraphFormat.SpaceBefore = 6
    r.ParagraphFormat.SpaceAfter = 10
    return p


def add_table(doc, headers, rows):
    n_rows = len(rows) + 1
    n_cols = len(headers)
    p = doc.Paragraphs.Add()
    table = doc.Tables.Add(p.Range, n_rows, n_cols)
    table.Borders.Enable = True
    for j, h in enumerate(headers, 1):
        cell = table.Cell(1, j)
        cell.Range.Text = h
        cell.Range.Font.Bold = True
        cell.Range.Font.Name = "Times New Roman"
        cell.Range.Font.Size = 12
    for i, row in enumerate(rows, 2):
        for j, val in enumerate(row, 1):
            cell = table.Cell(i, j)
            cell.Range.Text = str(val)
            cell.Range.Font.Name = "Times New Roman"
            cell.Range.Font.Size = 12
    doc.Paragraphs.Add()
    return table


